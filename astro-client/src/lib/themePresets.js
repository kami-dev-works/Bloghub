export function applyThemeAsCssVars(theme, mode) {
  const palette = mode === 'dark' ? theme.dark : theme.light;
  const root = document.documentElement;
  Object.entries(palette).forEach(([key, value]) => {
    root.style.setProperty(`--color-${key}`, value);
  });
}

export function mergeTheme(theme) {
  if (!theme || !theme.light || !theme.dark) return { ...DEFAULT_THEME };
  return {
    preset: theme.preset || 'default',
    light: { ...DEFAULT_THEME.light, ...theme.light },
    dark: { ...DEFAULT_THEME.dark, ...theme.dark },
  };
}
